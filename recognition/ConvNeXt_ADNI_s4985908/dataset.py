"""PyTorch dataset utilities for leakage-free ADNI slice classification.

The dataset reads ``slice_manifest.csv`` generated by ``scripts/audit_data.py``.
Splits are defined at subject level. Each JPEG is loaded as grayscale, converted
to three channels for ImageNet-pretrained ConvNeXt, resized, and normalized.
"""

from __future__ import annotations

import argparse
import csv
import random
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Sequence

import torch
from PIL import Image
from torch import Tensor
from torch.utils.data import DataLoader, Dataset, WeightedRandomSampler
from torchvision import transforms
from torchvision.transforms import InterpolationMode


IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)
VALID_SPLITS = ("train", "validation", "test")
TARGET_TO_CLASS = {0: "NC", 1: "AD"}


@dataclass(frozen=True)
class SliceRecord:
    """Metadata required to load one MRI slice."""

    image_path: Path
    subject_id: str
    scan_id: str
    slice_index: int
    target: int
    class_name: str
    split: str


def _parse_row(row: dict[str, str], row_number: int) -> SliceRecord:
    """Convert one CSV row to a validated SliceRecord."""
    try:
        target = int(row["target"])
        split = row["split"]
        class_name = row["class_name"]
        record = SliceRecord(
            image_path=Path(row["image_path"]),
            subject_id=row["subject_id"],
            scan_id=row["scan_id"],
            slice_index=int(row["slice_index"]),
            target=target,
            class_name=class_name,
            split=split,
        )
    except (KeyError, TypeError, ValueError) as error:
        raise ValueError(f"Invalid manifest row {row_number}: {row}") from error

    if record.target not in TARGET_TO_CLASS:
        raise ValueError(
            f"Manifest row {row_number} has unsupported target {record.target}"
        )
    if record.class_name != TARGET_TO_CLASS[record.target]:
        raise ValueError(
            f"Manifest row {row_number} has target/class mismatch: "
            f"{record.target}/{record.class_name}"
        )
    if record.split not in VALID_SPLITS:
        raise ValueError(
            f"Manifest row {row_number} has unsupported split {record.split!r}"
        )
    if not record.subject_id or not record.scan_id:
        raise ValueError(f"Manifest row {row_number} has an empty identifier")
    return record


def load_manifest(manifest_path: str | Path) -> list[SliceRecord]:
    """Load a slice manifest and validate patient-level split integrity."""
    path = Path(manifest_path)
    if not path.is_file():
        raise FileNotFoundError(
            f"Manifest not found: {path}. Run scripts/audit_data.py first."
        )

    with path.open("r", newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        required = {
            "image_path",
            "subject_id",
            "scan_id",
            "slice_index",
            "target",
            "class_name",
            "split",
        }
        missing = required - set(reader.fieldnames or ())
        if missing:
            raise ValueError(f"Manifest is missing columns: {sorted(missing)}")
        records = [
            _parse_row(row, row_number)
            for row_number, row in enumerate(reader, start=2)
        ]

    if not records:
        raise ValueError(f"Manifest contains no slice records: {path}")
    validate_patient_level_split(records)
    return records


def validate_patient_level_split(records: Sequence[SliceRecord]) -> None:
    """Ensure a subject has one label and belongs to exactly one split."""
    splits_by_subject: dict[str, set[str]] = defaultdict(set)
    targets_by_subject: dict[str, set[int]] = defaultdict(set)
    seen_paths: set[Path] = set()

    for record in records:
        if record.image_path in seen_paths:
            raise ValueError(f"Duplicate image path in manifest: {record.image_path}")
        seen_paths.add(record.image_path)
        splits_by_subject[record.subject_id].add(record.split)
        targets_by_subject[record.subject_id].add(record.target)

    split_conflicts = {
        subject_id: splits
        for subject_id, splits in splits_by_subject.items()
        if len(splits) != 1
    }
    if split_conflicts:
        examples = list(split_conflicts.items())[:10]
        raise ValueError(f"Patient leakage detected in manifest: {examples}")

    label_conflicts = {
        subject_id: targets
        for subject_id, targets in targets_by_subject.items()
        if len(targets) != 1
    }
    if label_conflicts:
        examples = list(label_conflicts.items())[:10]
        raise ValueError(f"Subjects with inconsistent labels: {examples}")


def build_transform(image_size: int = 224, training: bool = False) -> Callable:
    """Build conservative MRI transforms shared by both model families."""
    if image_size <= 0:
        raise ValueError("image_size must be positive")

    operations: list[Callable] = [
        transforms.Grayscale(num_output_channels=3),
        transforms.Resize(
            (image_size, image_size),
            interpolation=InterpolationMode.BILINEAR,
            antialias=True,
        ),
    ]
    if training:
        operations.append(
            transforms.RandomAffine(
                degrees=5.0,
                translate=(0.02, 0.02),
                scale=(0.95, 1.05),
                interpolation=InterpolationMode.BILINEAR,
                fill=0,
            )
        )
    operations.extend(
        [
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ]
    )
    return transforms.Compose(operations)


class ADNISliceDataset(Dataset[dict[str, Any]]):
    """ADNI JPEG slices from one leakage-free patient-level split."""

    def __init__(
        self,
        manifest_path: str | Path,
        split: str,
        image_size: int = 224,
        transform: Callable | None = None,
        verify_paths: bool = False,
    ) -> None:
        if split not in VALID_SPLITS:
            raise ValueError(f"split must be one of {VALID_SPLITS}, got {split!r}")

        all_records = load_manifest(manifest_path)
        self.records = [record for record in all_records if record.split == split]
        if not self.records:
            raise ValueError(f"No records found for split {split!r}")

        self.split = split
        self.transform = transform or build_transform(
            image_size=image_size, training=(split == "train")
        )

        if verify_paths:
            missing = [
                record.image_path
                for record in self.records
                if not record.image_path.is_file()
            ]
            if missing:
                raise FileNotFoundError(
                    f"{len(missing)} manifest images are missing; first: {missing[0]}"
                )

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, index: int) -> dict[str, Any]:
        record = self.records[index]
        with Image.open(record.image_path) as image:
            image = image.convert("L")
            tensor = self.transform(image)

        if not isinstance(tensor, Tensor):
            raise TypeError("The dataset transform must return a torch.Tensor")

        return {
            "image": tensor,
            "target": record.target,
            "subject_id": record.subject_id,
            "scan_id": record.scan_id,
            "slice_index": record.slice_index,
            "image_path": str(record.image_path),
        }

    @property
    def targets(self) -> list[int]:
        """Return slice targets in dataset order."""
        return [record.target for record in self.records]


def make_subject_and_class_balanced_sampler(
    dataset: ADNISliceDataset, seed: int = 3710
) -> WeightedRandomSampler:
    """Balance classes while giving each subject equal total sampling weight.

    A subject with many visits must not dominate training. Each slice weight is
    inversely proportional to both the number of slices for its subject and the
    number of subjects in its diagnostic class.
    """
    slices_per_subject = Counter(record.subject_id for record in dataset.records)
    subjects_by_target: dict[int, set[str]] = defaultdict(set)
    for record in dataset.records:
        subjects_by_target[record.target].add(record.subject_id)

    weights = []
    for record in dataset.records:
        subject_slice_count = slices_per_subject[record.subject_id]
        class_subject_count = len(subjects_by_target[record.target])
        weights.append(1.0 / (subject_slice_count * class_subject_count))

    generator = torch.Generator()
    generator.manual_seed(seed)
    return WeightedRandomSampler(
        weights=torch.as_tensor(weights, dtype=torch.double),
        num_samples=len(dataset),
        replacement=True,
        generator=generator,
    )


def _seed_worker(worker_id: int) -> None:
    """Seed Python randomness in DataLoader workers from PyTorch's seed."""
    del worker_id
    random.seed(torch.initial_seed() % (2**32))


def create_dataloader(
    manifest_path: str | Path,
    split: str,
    batch_size: int = 32,
    image_size: int = 224,
    num_workers: int = 4,
    seed: int = 3710,
    balanced_training: bool = True,
    verify_paths: bool = False,
) -> tuple[ADNISliceDataset, DataLoader]:
    """Create a reproducible DataLoader for one patient-level split."""
    if batch_size <= 0:
        raise ValueError("batch_size must be positive")
    if num_workers < 0:
        raise ValueError("num_workers cannot be negative")

    dataset = ADNISliceDataset(
        manifest_path=manifest_path,
        split=split,
        image_size=image_size,
        verify_paths=verify_paths,
    )

    sampler = None
    shuffle = split == "train"
    if split == "train" and balanced_training:
        sampler = make_subject_and_class_balanced_sampler(dataset, seed=seed)
        shuffle = False

    generator = torch.Generator()
    generator.manual_seed(seed)
    loader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        sampler=sampler,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        persistent_workers=num_workers > 0,
        worker_init_fn=_seed_worker,
        generator=generator,
    )
    return dataset, loader


def main() -> None:
    """Load one batch as a quick dataset smoke test."""
    parser = argparse.ArgumentParser(description="Smoke-test the ADNI DataLoader")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--split", choices=VALID_SPLITS, default="train")
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--image-size", type=int, default=224)
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument("--seed", type=int, default=3710)
    parser.add_argument("--verify-paths", action="store_true")
    args = parser.parse_args()

    dataset, loader = create_dataloader(
        manifest_path=args.manifest,
        split=args.split,
        batch_size=args.batch_size,
        image_size=args.image_size,
        num_workers=args.num_workers,
        seed=args.seed,
        verify_paths=args.verify_paths,
    )
    batch = next(iter(loader))
    print(f"split={args.split}")
    print(f"slices={len(dataset)}")
    print(f"batch image shape={tuple(batch['image'].shape)}")
    print(f"batch targets={batch['target'].tolist()}")
    print(f"batch subjects={list(batch['subject_id'])}")


if __name__ == "__main__":
    main()
